/*
 * /method — the method reading page (Product Specification §14, §17; Final Design §7.7).
 * Content is owned by GET /api/method (src/server/method.ts): this screen renders it
 * verbatim and adds no claims of its own, so the documentation can never drift from the
 * endpoint that serves it. Layout follows Final Design §7.7: a Tufte-style reading page in
 * ink-on-paper tokens; the margin column carries the provenance badges so evidence-vs-
 * inference is visible without scrolling.
 */
import { useCallback, useEffect, useState } from "react";
import { ApiClientError, getMethod } from "../lib/api";
import type { MethodContent } from "../../shared/routes";
import "./method.css";

type LoadState =
  | { status: "loading" }
  | { status: "loaded"; method: MethodContent }
  | { status: "failed"; message: string; code: string };

export function MethodRoute() {
  const [state, setState] = useState<LoadState>({ status: "loading" });

  const load = useCallback(async () => {
    setState({ status: "loading" });
    try {
      const method = await getMethod();
      setState({ status: "loaded", method });
    } catch (error) {
      const apiError = error instanceof ApiClientError ? error : undefined;
      setState({
        status: "failed",
        message: apiError?.message ?? "Zorq could not load the method content.",
        code: apiError?.code ?? "NETWORK_ERROR"
      });
    }
  }, []);

  useEffect(() => {
    void load();
  }, [load]);

  if (state.status === "loading") {
    return (
      <main className="method-page">
        <h1 className="method-title">How Zorq measures</h1>
        <p className="method-loading">Loading the method…</p>
      </main>
    );
  }

  if (state.status === "failed") {
    return (
      <main className="method-page">
        <h1 className="method-title">How Zorq measures</h1>
        <p className="method-error" role="alert">
          {state.message} <span className="method-error-code">({state.code})</span>
        </p>
        <button className="method-retry" type="button" onClick={() => void load()}>
          Retry
        </button>
      </main>
    );
  }

  const { method } = state;

  return (
    <main className="method-page">
      <header className="method-heading">
        <p className="method-stamp">Method · rev {method.updated}</p>
        <h1 className="method-title">{method.title}</h1>
        <p className="method-intro">{method.evidenceVsInference.rule}</p>
      </header>

      <div className="method-layout">
        <div className="method-main">
          <section aria-labelledby="method-qloo">
            <h2 id="method-qloo" className="method-section-title">Measured by Qloo</h2>
            <ul className="method-list">
              {method.whatQlooMeasures.map((item) => (
                <li key={item}>{item}</li>
              ))}
            </ul>
          </section>

          <section aria-labelledby="method-zorq">
            <h2 id="method-zorq" className="method-section-title">Computed by Zorq</h2>
            <ul className="method-list">
              {method.whatZorqComputes.map((item) => (
                <li key={item}>{item}</li>
              ))}
            </ul>
          </section>

          <section aria-labelledby="method-llm">
            <h2 id="method-llm" className="method-section-title">Generated by the LLM</h2>
            <ul className="method-list">
              {method.whatTheLlmGenerates.map((item) => (
                <li key={item}>{item}</li>
              ))}
            </ul>
          </section>

          <section aria-labelledby="method-formulas">
            <h2 id="method-formulas" className="method-section-title">The formulas</h2>
            <ol className="method-formulas">
              {method.formulas.map((formula) => (
                <li key={formula}>
                  <code className="method-formula">{formula}</code>
                </li>
              ))}
            </ol>
          </section>

          <section aria-labelledby="method-example">
            <h2 id="method-example" className="method-section-title">{method.workedExample.title}</h2>
            <p className="method-intro">{method.workedExample.intro}</p>
            <ol className="method-steps">
              {method.workedExample.steps.map((step) => (
                <li key={step}>{step}</li>
              ))}
            </ol>
          </section>

          <section aria-labelledby="method-heuristics">
            <h2 id="method-heuristics" className="method-section-title">Heuristics (labelled, editable in intent)</h2>
            <table className="method-heuristics">
              <thead>
                <tr>
                  <th scope="col">Rule</th>
                  <th scope="col">Detail</th>
                  <th scope="col">Provenance</th>
                </tr>
              </thead>
              <tbody>
                {method.heuristics.map((heuristic) => (
                  <tr key={heuristic.name}>
                    <td className="method-heuristic-name">
                      {heuristic.name}
                      <span className="method-editable">{heuristic.editable ? " · editable" : " · fixed"}</span>
                    </td>
                    <td>{heuristic.detail}</td>
                    <td className="method-heuristic-note">{heuristic.note}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </section>

          <section aria-labelledby="method-limits">
            <h2 id="method-limits" className="method-section-title">Known limits</h2>
            <ul className="method-list">
              {method.knownLimits.map((limit) => (
                <li key={limit}>{limit}</li>
              ))}
            </ul>
          </section>

          <section aria-labelledby="method-setup">
            <h2 id="method-setup" className="method-section-title">Open source and how to run it</h2>
            <p className="method-intro">{method.setupSummary}</p>
          </section>
        </div>

        <aside className="method-margin" aria-label="Evidence versus inference">
          <h2 className="method-margin-title">Evidence vs inference</h2>
          {method.evidenceVsInference.badges.map((badge) => (
            <p className="method-badge-entry" key={badge.badge}>
              <span className="method-badge">{badge.badge}</span> {badge.meaning}
            </p>
          ))}
        </aside>
      </div>
    </main>
  );
}
